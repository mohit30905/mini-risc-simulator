; ============================================================================
; shifts.asm — Shift operation demo
; ============================================================================
; Expected results:
;   R1 = 1,   R2 = 16  (1 << 4)
;   R3 = 255, R4 = 15  (255 >> 4)
;   R5 = 128  (1 << 7)
;   R6 = 1    (128 >> 7)
; ============================================================================

MOVI R1, 1         ; R1 = 1
SHL  R2, R1, 4     ; R2 = 1 << 4 = 16
MOVI R3, 255       ; R3 = 0xFF
SHR  R4, R3, 4     ; R4 = 255 >> 4 = 15
SHL  R5, R1, 7     ; R5 = 1 << 7 = 128
SHR  R6, R5, 7     ; R6 = 128 >> 7 = 1
HALT

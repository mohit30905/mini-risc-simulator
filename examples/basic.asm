; ============================================================================
; basic.asm — Basic arithmetic demo
; ============================================================================
; Expected results:
;   R1 = 10,  R2 = 20,  R3 = 30 (ADD),  R4 = 10 (SUB),  R5 = 30 (XOR)
; ============================================================================

MOVI R1, 10       ; Load 10 into R1
MOVI R2, 20       ; Load 20 into R2
ADD  R3, R1, R2   ; R3 = R1 + R2 = 30
SUB  R4, R2, R1   ; R4 = R2 - R1 = 10
XOR  R5, R1, R2   ; R5 = R1 XOR R2 = 10 XOR 20 = 30
HALT              ; Stop execution

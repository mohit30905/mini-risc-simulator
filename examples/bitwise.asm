; ============================================================================
; bitwise.asm — Bitwise operation demo
; ============================================================================
; Expected results:
;   R1 = 255 (0xFF),  R2 = 15 (0x0F)
;   R3 = 15  (AND),   R4 = 255 (OR),   R5 = 240 (XOR = 0xF0)
; ============================================================================

MOVI R1, 0xFF     ; R1 = 255  (binary: 0000 0000 1111 1111)
MOVI R2, 0x0F     ; R2 = 15   (binary: 0000 0000 0000 1111)
AND  R3, R1, R2   ; R3 = R1 AND R2 = 0x0F = 15
OR   R4, R1, R2   ; R4 = R1 OR  R2 = 0xFF = 255
XOR  R5, R1, R2   ; R5 = R1 XOR R2 = 0xF0 = 240
HALT
